import crypto from 'crypto';
import bcrypt from 'bcrypt';
import { isUniqueViolation } from '../database/db';
import * as otpsRepo from '../database/repos/otps';
import * as usersRepo from '../database/repos/users';
import { config } from '../config/env';
import { hasColumn, hasTable } from './schemaGuard';
import { normalizePhone, sendAuthenticationTemplate, sendAuthenticationTemplateDetailed, sendOnce, logMessage, isWhatsappConfigured, WHATSAPP_TEMPLATES } from './whatsappService';
import { customerMessageForKind, statusForKind } from './metaErrors';
import { canonicalPhone, phoneVariants, placeholderEmailFor } from '../utils/phone';
import { hashOtpCode, verifyOtpCode } from '../utils/otpHash';

const OTP_TTL_MINUTES = 5;
const OTP_MAX_ATTEMPTS = 5;
const RESEND_COOLDOWN_SECONDS = 30;
const PURPOSE = 'checkout_login';

/**
 * A code is exactly six digits, generated by crypto.randomInt over
 * [100000, 1000000) — so it is always "100000".."999999", never shorter and
 * never padded.
 *
 * Whitespace is removed before the length check so a pasted "123 456" still
 * works (that has always been accepted), but nothing else is stripped: a
 * malformed submission is rejected before the store is touched, so it can never
 * consume one of the five attempts.
 */
const OTP_PATTERN = /^[0-9]{6}$/;

/** Remove whitespace only — never arbitrary non-digits. */
function normalizeOtpSubmission(code: unknown): string {
  return String(code ?? '').replace(/\s+/g, '');
}

export type OtpFailureReason = 'not_found' | 'expired' | 'already_used' | 'too_many_attempts' | 'invalid';

/**
 * `otps` is created by database/deltas/005. Refuse with a clear 503 rather than
 * letting PostgREST's missing-table error bubble up as an opaque 500 — the
 * checkout step this powers cannot fall back to anything else.
 */
async function assertOtpStoreAvailable(): Promise<void> {
  if (await hasTable('otps')) return;
  console.error('[OTP] Table "otps" is missing — apply database/deltas/005_otp_whatsapp_review_requests.sql.');
  throw Object.assign(new Error('Sign-in with OTP is temporarily unavailable. Please try again shortly.'), {
    status: 503,
  });
}

export const otpService = {
  ttlMinutes: OTP_TTL_MINUTES,
  resendCooldownSeconds: RESEND_COOLDOWN_SECONDS,
  maxAttempts: OTP_MAX_ATTEMPTS,

  /**
   * Generate + deliver a 6-digit OTP over WhatsApp.
   * Returns { expiresInSeconds } on success, or throws with a user-friendly message.
   */
  async sendOtp(phoneRaw: string): Promise<{ expiresInSeconds: number; devOtp?: string }> {
    const phone = normalizePhone(phoneRaw);
    if (!phone || phone.length < 10) {
      throw Object.assign(new Error('Please enter a valid mobile number.'), { status: 400 });
    }

    await assertOtpStoreAvailable();

    // Cooldown so the endpoint cannot be abused for spam. Deliberately NOT
    // filtered on consumed_at: a code that was just verified must still hold
    // the cooldown, otherwise verifying and immediately re-sending is a free
    // extra send on every request.
    const recentCreatedAt = await otpsRepo.latestCreatedAt(phone, PURPOSE);

    if (recentCreatedAt) {
      const ageSeconds = (Date.now() - new Date(recentCreatedAt).getTime()) / 1000;
      if (ageSeconds < RESEND_COOLDOWN_SECONDS) {
        throw Object.assign(
          new Error(`Please wait ${Math.ceil(RESEND_COOLDOWN_SECONDS - ageSeconds)}s before requesting a new code.`),
          { status: 429 }
        );
      }
    }

    // Exactly six digits from a CSPRNG. The upper bound is exclusive, so
    // 100000..999999 with no modulo bias and no zero-padding needed.
    const code = String(crypto.randomInt(100000, 1000000));
    const expiresAt = new Date(Date.now() + OTP_TTL_MINUTES * 60 * 1000).toISOString();

    const inserted = await otpsRepo.insertOtp({
      phone,
      code_hash: hashOtpCode(code, phone),
      purpose: PURPOSE,
      attempts: 0,
      max_attempts: OTP_MAX_ATTEMPTS,
      expires_at: expiresAt,
    });

    // AUTHENTICATION-category template: the code is delivered as the body
    // parameter AND as the copy-code button parameter at index 0. The template
    // name and language are resolved from Meta at runtime, so an approval that
    // lands after deploy activates this path with no redeploy.
    //
    // There is deliberately no plaintext fallback: Meta rejects a free-form
    // message outside the 24h service window anyway, and a second delivery
    // path is a second way for the code to leak.
    const send = await sendAuthenticationTemplateDetailed(phone, code);
    const delivered = send.delivered;

    // Record every attempt — sent or failed — without ever writing the code.
    await logMessage({
      recipient: phone,
      templateName: send.templateName || config.whatsappOtpTemplateName || WHATSAPP_TEMPLATES.OTP,
      messageType: 'authentication_template',
      purpose: 'otp_send',
      referenceId: String(inserted.id),
      status: delivered ? 'sent' : 'failed',
      error: delivered
        ? undefined
        : `Meta rejected the authentication template message (kind=${send.errorKind || 'unknown'}, code=${send.errorCode ?? 'n/a'})`,
      payload: { channel: 'whatsapp', expiresAt },
    });

    if (!delivered) {
      // Meta rejected the message (bad token, unapproved template, malformed
      // phone, rate limit) or WhatsApp is not configured at all. Reporting
      // success here would show the customer "we sent a code" for a message that
      // will never arrive, and the failure would only surface as an unexplained
      // timeout at verify time. Fail loudly instead.
      //
      // The stored row is rolled back too: the code never left the building, so
      // leaving it would make the resend cooldown block a retry that could
      // actually succeed.
      await otpsRepo.deleteOtp(inserted.id).catch(() => undefined);
      const kind = send.errorKind || 'service';
      console.error(
        `[OTP] WhatsApp delivery failed (kind=${kind}, metaCode=${send.errorCode ?? 'n/a'}) — the code was NOT sent. ` +
          'Check WHATSAPP_API_TOKEN, WHATSAPP_PHONE_NUMBER_ID and that the Meta template is approved.'
      );
      throw Object.assign(new Error(customerMessageForKind(kind)), {
        status: statusForKind(kind),
        code: 'OTP_DELIVERY_FAILED',
      });
    }

    return {
      expiresInSeconds: OTP_TTL_MINUTES * 60,
      // Dev convenience only, and deliberately double-gated: never when
      // NODE_ENV=production, and never once real Meta credentials are present
      // (a deployment with a live token is a real deployment even if
      // NODE_ENV was forgotten).
      ...(config.nodeEnv !== 'production' && !isWhatsappConfigured() ? { devOtp: code } : {}),
    };
  },

  /** Validate a code. Consumes the row on success. */
  async verifyOtp(phoneRaw: string, code: string): Promise<{ ok: true } | { ok: false; reason: OtpFailureReason }> {
    const phone = normalizePhone(phoneRaw);
    const submitted = normalizeOtpSubmission(code);
    if (!phone || !OTP_PATTERN.test(submitted)) return { ok: false, reason: 'invalid' };

    await assertOtpStoreAvailable();

    const row = await otpsRepo.findActive(phone, PURPOSE);
    if (!row) return { ok: false, reason: 'not_found' };
    if (new Date(row.expires_at).getTime() < Date.now()) return { ok: false, reason: 'expired' };
    if (Number(row.attempts) >= Number(row.max_attempts)) return { ok: false, reason: 'too_many_attempts' };

    if (!verifyOtpCode(submitted, phone, row.code_hash)) {
      await otpsRepo.incrementAttempts(row.id);
      const remaining = Number(row.max_attempts) - (Number(row.attempts) + 1);
      if (remaining <= 0) return { ok: false, reason: 'too_many_attempts' };
      return { ok: false, reason: 'invalid' };
    }

    // Atomic single use: the update is guarded on consumed_at IS NULL and the
    // returned rows are checked. Without the guard two concurrent verifies of
    // the same code both read an unconsumed row, both pass the hash check, and
    // both mint a JWT from one code. With it, exactly one update matches.
    const consumed = await otpsRepo.consume(row.id);
    if (!consumed) {
      // Lost the race: someone else consumed this exact row first.
      return { ok: false, reason: 'already_used' };
    }

    return { ok: true };
  },

  /**
   * Login-or-register on OTP verification.
   * - number not found  => auto-create the customer (register)
   * - number found      => log them in and refresh name/phone (login)
   * Returns the user row (snake_case) ready for JWT issue.
   */
  async findOrCreateUserByPhone(phoneRaw: string, name?: string) {
    const phone = canonicalPhone(phoneRaw) || normalizePhone(phoneRaw);
    if (!phone) throw Object.assign(new Error('Please enter a valid mobile number.'), { status: 400 });

    const variants = phoneVariants(phoneRaw);
    const lookup = variants.length > 0 ? variants : [phone];

    const existing = await usersRepo.findByPhoneVariants(lookup, '*');

    if (existing) {
      const user = existing;
      const patch: any = { updated_at: new Date().toISOString() };
      // `users.last_login_at` arrives in delta 005 — never let a missing
      // timestamp column roll back the name/phone refresh below.
      if (await hasColumn('users', 'last_login_at')) {
        patch.last_login_at = new Date().toISOString();
      }
      if (name && !user.first_name) {
        const [firstName, ...rest] = name.trim().split(/\s+/);
        patch.first_name = firstName || user.first_name;
        if (rest.length) patch.last_name = rest.join(' ');
      }
      const updated = await usersRepo.updateUser(user.id, patch);
      return { user: updated || user, created: false };
    }

    // users.email / password_hash are NOT NULL + UNIQUE in the base schema, so a
    // phone-only customer gets a deterministic placeholder identity.
    const placeholderEmail = placeholderEmailFor(phone);
    const passwordHash = await bcrypt.hash(crypto.randomBytes(32).toString('hex'), 10);
    const [firstName, ...rest] = (name || '').trim().split(/\s+/);

    const insertData: any = {
      email: placeholderEmail,
      password_hash: passwordHash,
      first_name: firstName || null,
      last_name: rest.length ? rest.join(' ') : null,
      phone,
      role: 'customer',
      active: true,
    };
    if (await hasColumn('users', 'last_login_at')) {
      insertData.last_login_at = new Date().toISOString();
    }

    let created: any;
    try {
      created = await usersRepo.insertUser(insertData, '*');
    } catch (error: any) {
      // UNIQUE violation = a racing request created it first; re-read.
      if (isUniqueViolation(error)) {
        const retry = await usersRepo.findByPhoneVariants(lookup, '*');
        if (retry) return { user: retry, created: false };
      }
      throw error;
    }

    // Welcome message — never blocks the login flow.
    sendOnce({
      to: phone,
      purpose: 'welcome',
      referenceId: `welcome:${phone}`,
      template: WHATSAPP_TEMPLATES.WELCOME,
      params: [created.first_name || 'there'],
      fallbackText: 'Welcome to MeruVeda! Your account has been created.',
    }).catch(() => undefined);

    return { user: created, created: true };
  },
};
